#!/usr/bin/env python3
"""make_basebase_tables.py -- LaTeX tables for the Base+Base control (appendix).

Run from the repository root after base_base_control.py:
    python3 evaluation/make_basebase_tables.py > eval/basebase_tables.tex
Reads eval/base_base_control.csv and the bootstrap lines of eval/base_base_control.txt.
"""
import re
import numpy as np
import pandas as pd

W = 0.55
DS = ["OpinionQA", "GOQA", "GSS", "ISSP"]
M = ["gemma4-12b", "gemma4-31b", "qwen36-27b", "phi4-14b", "mistral-24b", "gptoss-20b", "exaone-32b"]
NAMES = {"gemma4-12b": "Gemma-4-12B", "gemma4-31b": "Gemma-4-31B", "qwen36-27b": "Qwen3.6-27B", "phi4-14b": "Phi-4-14B",
         "mistral-24b": "Mistral-24B", "gptoss-20b": "gpt-oss-20B", "exaone-32b": "EXAONE-32B"}
R = pd.read_csv("eval/base_base_control.csv")
R = R[np.isclose(R.w, W)]
txt = open("eval/base_base_control.txt").read()
ci = {}
for ds, lab, met, pt, lo, hi in re.findall(r"^\s+(\w+)\s+(vs Base\+Base_j)\s+(JS|Rep)\s+clusters\s+\d+\s+diff ([+-][\d.]+)\s+CI \[([+-][\d.]+), ([+-][\d.]+)\]", txt, re.M):
    ci[(ds, met)] = (float(pt), float(lo), float(hi))


def sg(x):
    return f"${x:+.4f}$".replace("-", "-")


def pair_wins(ds, met):
    D = R[R.dataset == ds]
    a = D[D.cond == "NT"].set_index(["model", "partner"])[met]
    b = D[D.cond == "BB"].set_index(["model", "partner"])[met]
    j = pd.concat([a, b], axis=1, keys=["nt", "bb"]).dropna()
    return int(((j.nt < j.bb) if met == "JS" else (j.nt > j.bb)).sum()), len(j)


print("%%%% ===== from tables/basebase.tex (generated by evaluation/make_basebase_tables.py) =====")
print(r"""\begin{table*}[t]
\centering\small
\setlength{\tabcolsep}{4pt}
\resizebox{\textwidth}{!}{%
\begin{tabular}{@{}l rrrc c rrrc@{}}
\toprule
 & \multicolumn{4}{c}{JS (lower is better)} & & \multicolumn{4}{c}{Rep (higher is better)} \\
\cmidrule(lr){2-5}\cmidrule(l){7-10}
Dataset & Mixture & Base+Base & $\Delta$ [95\% CI] & Won & & Mixture & Base+Base & $\Delta$ [95\% CI] & Won \\
\midrule""")
for ds in DS:
    D = R[R.dataset == ds]
    cells = []
    for met in ("JS", "Rep"):
        nt = D[D.cond == "NT"].groupby("model")[met].mean().mean()
        bb = D[D.cond == "BB"].groupby("model")[met].mean().mean()
        pt, lo, hi = ci[(ds, met)]
        w, n = pair_wins(ds, met)
        better_nt = nt < bb if met == "JS" else nt > bb
        f = lambda v, b: (r"\textbf{%.4f}" % v) if b else "%.4f" % v
        cells.append((f(nt, better_nt), f(bb, not better_nt), f"${pt:+.4f}$ $[{lo:+.4f},{hi:+.4f}]$", f"{w}/{n}"))
    print(f"{ds:9s} & {cells[0][0]} & {cells[0][1]} & {cells[0][2]} & {cells[0][3]} & & {cells[1][0]} & {cells[1][1]} & {cells[1][2]} & {cells[1][3]} \\\\")
print(r"""\bottomrule
\end{tabular}}
\caption{\label{tab:basebase}Mixture of Base and \nt{} compared with the mixture of Base and another Base model, both at weight $0.55$. Base+Base is the mean over the six other models as partner, and the mean is taken over seven target models. $\Delta$ is Base+Base minus Mixture for JS and Mixture minus Base+Base for Rep, so positive values favor the mixture, with 95\% cluster-bootstrap intervals (2,000 resamples). Won counts the 42 target--partner pairs on which the mixture is better.}
\end{table*}
""")

print("%%%% ===== from tables/basebase_models.tex (generated) =====")
print(r"""\begin{table*}[t]
\centering\small
\setlength{\tabcolsep}{3.2pt}
\resizebox{\textwidth}{!}{%
\begin{tabular}{@{}l rr rr rr rr c rr rr rr rr@{}}
\toprule
 & \multicolumn{8}{c}{JS (lower is better)} & & \multicolumn{8}{c}{Rep (higher is better)} \\
\cmidrule(lr){2-9}\cmidrule(l){11-18}
 & \multicolumn{2}{c}{OpinionQA} & \multicolumn{2}{c}{GOQA} & \multicolumn{2}{c}{GSS} & \multicolumn{2}{c}{ISSP} & & \multicolumn{2}{c}{OpinionQA} & \multicolumn{2}{c}{GOQA} & \multicolumn{2}{c}{GSS} & \multicolumn{2}{c}{ISSP} \\
Model & Mix & BB & Mix & BB & Mix & BB & Mix & BB & & Mix & BB & Mix & BB & Mix & BB & Mix & BB \\
\midrule""")
for m in M:
    row = []
    for met in ("JS", "Rep"):
        for ds in DS:
            D = R[(R.dataset == ds) & (R.model == m)]
            nt = D[D.cond == "NT"][met].mean(); bb = D[D.cond == "BB"][met].mean()
            b = nt < bb if met == "JS" else nt > bb
            row += [(r"\textbf{%.4f}" % nt) if b else "%.4f" % nt, ("%.4f" % bb) if b else (r"\textbf{%.4f}" % bb)]
        if met == "JS":
            row.append("")
    print(f"{NAMES[m]:12s} & " + " & ".join(row) + r" \\")
print(r"""\bottomrule
\end{tabular}}
\caption{\label{tab:basebase_models}Per-model comparison at weight $0.55$. Mix is the mixture of Base and \nt, and BB is the mean over the six Base+Base mixtures that use each other model as the partner. The better value in each pair is in bold.}
\end{table*}
""")
